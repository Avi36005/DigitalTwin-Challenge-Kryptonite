"""Deterministic, clearly fictional synthetic participants.

Synthetic data proves the software workflow (replay, contracts, edge cases). It is NOT derived from,
copied from or perturbed from any CGMacros participant, and nothing computed on it is clinical
evidence. Every record carries ``source = "synthetic:glucotwin-generator"`` and the store is marked
with an explicit synthetic license (CC0-1.0, generated by this repository's code).

Scenarios
---------
* ``SYN-A`` normal operation
* ``SYN-B`` rising glucose with frequent sustained highs
* ``SYN-C`` delayed meal logging (meal records become available 90 minutes after the meal)
* ``SYN-D`` sensor gaps and sensor-limit readings
* ``SYN-E`` insufficient history (short, interrupted record)
* ``SYN-T01..SYN-T12`` hidden training participants for the synthetic demonstration model
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

from glucotwin.data.store import PatientData, Store

SOURCE = "synthetic:glucotwin-generator"
GENERATOR_VERSION = "synthetic-1.0"
LICENSE = "CC0-1.0 (synthetic data generated by GlucoTwin code; no real participants)"
ORIGIN = pd.Timestamp("2000-01-03T00:00:00Z")


@dataclass(frozen=True)
class Scenario:
    patient_id: str
    alias: str
    description: str
    days: float
    seed: int
    baseline: float
    sensitivity: float          # mg/dL peak per gram of carbohydrate
    meal_delay_minutes: float = 0.0
    gaps: tuple[tuple[float, float], ...] = ()   # (start hour, duration minutes)
    limit_readings: int = 0
    visible: bool = True
    truncate_hours: float | None = None


SCENARIOS: list[Scenario] = [
    Scenario("SYN-A", "Synthetic Participant A", "Normal operation", 4, 101, 128, 1.15),
    Scenario("SYN-B", "Synthetic Participant B", "Rising glucose with frequent sustained highs", 4, 102, 158, 1.9),
    Scenario("SYN-C", "Synthetic Participant C", "Delayed meal logging (90 minutes)", 4, 103, 138, 1.4,
             meal_delay_minutes=90),
    Scenario("SYN-D", "Synthetic Participant D", "Sensor gaps and sensor-limit readings", 4, 104, 145, 1.5,
             gaps=((10.0, 45), (31.0, 150), (55.5, 25), (78.0, 240)), limit_readings=3),
    Scenario("SYN-E", "Synthetic Participant E", "Insufficient history (short, interrupted record)", 0.25, 105,
             150, 1.5, gaps=((1.0, 90),)),
] + [
    Scenario(f"SYN-T{i:02d}", f"Synthetic training participant {i:02d}", "Hidden training participant",
             7, 200 + i, 115 + 5 * (i % 9), 0.9 + 0.12 * (i % 8), visible=False)
    for i in range(1, 13)
]


def _gamma_kernel(t: np.ndarray, peak_minutes: float) -> np.ndarray:
    """Unit-peak meal response shape; zero before the meal."""
    k = 2.0
    theta = peak_minutes / (k - 1)
    x = np.clip(t, 0, None) / theta
    shape = x ** (k - 1) * np.exp(-x)
    peak = ((k - 1) ** (k - 1)) * np.exp(-(k - 1))
    return np.where(t > 0, shape / peak, 0.0)


def generate(s: Scenario) -> PatientData:
    rng = np.random.default_rng(s.seed)
    minutes = int(s.days * 24 * 60)
    grid = np.arange(0, minutes, 1.0)

    # Meals: breakfast, lunch, dinner (+ occasional snack)
    meals = []
    for day in range(int(np.ceil(s.days))):
        for name, hour, carbs in (("Breakfast", 8.0, 45), ("Lunch", 13.0, 70), ("Dinner", 19.5, 65)):
            t = day * 1440 + hour * 60 + rng.normal(0, 25)
            if 0 <= t < minutes:
                c = max(10.0, rng.normal(carbs, 18))
                meals.append((t, name, c))
        if rng.random() < 0.35:
            t = day * 1440 + 16 * 60 + rng.normal(0, 40)
            if 0 <= t < minutes:
                meals.append((t, "Snack", max(5.0, rng.normal(20, 6))))
    meals.sort()

    # Activity: per-minute METs with walking bouts
    mets = np.full(grid.size, 1.2) + rng.normal(0, 0.1, grid.size)
    night = ((grid % 1440) < 6 * 60) | ((grid % 1440) > 23 * 60)
    mets[night] = 0.95
    for day in range(int(np.ceil(s.days))):
        for _ in range(rng.integers(1, 4)):
            start = int(day * 1440 + rng.uniform(9, 21) * 60)
            dur = int(rng.uniform(10, 45))
            mets[start:start + dur] = rng.uniform(3.0, 5.5)
    mets = np.clip(mets, 0.9, 8)
    hr = 62 + 14 * (mets - 1) + rng.normal(0, 3, grid.size)

    # Glucose dynamics
    g = np.full(grid.size, s.baseline, dtype=float)
    for t, _, c in meals:
        g += c * s.sensitivity * _gamma_kernel(grid - t, peak_minutes=55 + 10 * rng.random())
    activity_effect = np.convolve(np.clip(mets - 2.0, 0, None), np.exp(-np.arange(0, 120) / 40.0), mode="full")
    g -= 0.9 * activity_effect[: grid.size]
    g += 8 * np.sin(2 * np.pi * (grid % 1440) / 1440 - 1.2)  # mild daily rhythm (synthetic)
    ar = np.zeros(grid.size)
    eps = rng.normal(0, 0.9, grid.size)
    for i in range(1, grid.size):
        ar[i] = 0.985 * ar[i - 1] + eps[i]
    g += ar * 2.0

    # Native-like 5-minute sensor samples with jitter and sensor noise
    sample_t = np.arange(2.0, minutes, 5.0) + rng.uniform(-0.15, 0.15, size=len(np.arange(2.0, minutes, 5.0)))
    sample_v = np.interp(sample_t, grid, g) + rng.normal(0, 3.0, sample_t.size)
    sample_v = np.clip(np.round(sample_v), 40, 400)
    keep = np.ones(sample_t.size, dtype=bool)
    for start_h, dur in s.gaps:
        keep &= ~((sample_t >= start_h * 60) & (sample_t < start_h * 60 + dur))
    if s.truncate_hours is not None:
        keep &= sample_t < s.truncate_hours * 60
    flags = np.array([""] * sample_t.size, dtype=object)
    quality = np.array(["ok"] * sample_t.size, dtype=object)
    if s.limit_readings:
        idx = rng.choice(np.where(keep)[0], size=s.limit_readings, replace=False)
        sample_v[idx] = 400.0
        quality[idx] = "suspect"
        flags[idx] = "sensor_limit_value"
    sample_t, sample_v, quality, flags = sample_t[keep], sample_v[keep], quality[keep], flags[keep]

    ts = ORIGIN + pd.to_timedelta(sample_t, unit="min")
    glucose = pd.DataFrame({
        "event_id": [f"{s.patient_id}-g-{i:05d}" for i in range(sample_t.size)],
        "observed_at": ts, "available_at": ts,
        "value_mg_dl": sample_v.astype(float),
        "quality": quality.astype(str), "flags": flags.astype(str), "source": SOURCE,
    })

    # Activity summaries: trailing 5-minute windows ending on the 5-minute grid
    ends = np.arange(5, minutes + 1, 5)
    a_rows = []
    for j, e in enumerate(ends):
        sl = slice(e - 5, e)
        a_rows.append((f"{s.patient_id}-a-{j:05d}", e, float(np.mean(hr[sl])), float(np.mean(mets[sl])),
                       float(np.sum(mets[sl]) * 1.2)))
    a_df = pd.DataFrame(a_rows, columns=["event_id", "end", "heart_rate_bpm", "mets", "activity_kcal"])
    a_ts = ORIGIN + pd.to_timedelta(a_df["end"], unit="min")
    if s.truncate_hours is not None:
        a_df = a_df[a_df["end"] <= s.truncate_hours * 60]
        a_ts = a_ts[a_df.index]
    activity = pd.DataFrame({
        "event_id": a_df["event_id"], "observed_at": a_ts, "available_at": a_ts,
        "window_minutes": 5, "minutes_covered": 5,
        "heart_rate_bpm": a_df["heart_rate_bpm"].round(1), "mets": a_df["mets"].round(2),
        "activity_kcal": a_df["activity_kcal"].round(2),
        "quality": "ok", "flags": "", "source": SOURCE,
    })

    m_rows = []
    for j, (t, name, c) in enumerate(meals):
        if s.truncate_hours is not None and t >= s.truncate_hours * 60:
            continue
        obs = ORIGIN + pd.Timedelta(minutes=float(t))
        avail = obs + pd.Timedelta(minutes=s.meal_delay_minutes)
        protein, fat, fiber = c * 0.35, c * 0.3, c * 0.08
        m_rows.append({
            "event_id": f"{s.patient_id}-m-{j:03d}", "observed_at": obs, "available_at": avail,
            "meal_type": name, "energy_kcal": round(4 * c + 4 * protein + 9 * fat, 1), "carbs_g": round(c, 1),
            "protein_g": round(protein, 1), "fat_g": round(fat, 1), "fiber_g": round(fiber, 1),
            "amount_consumed_pct": 100.0,
            "quality": "ok" if s.meal_delay_minutes == 0 else "estimated",
            "flags": "" if s.meal_delay_minutes == 0 else f"logged_late_{int(s.meal_delay_minutes)}min",
            "source": SOURCE,
        })
    meals_df = pd.DataFrame(m_rows) if m_rows else pd.DataFrame(columns=[
        "event_id", "observed_at", "available_at", "meal_type", "energy_kcal", "carbs_g", "protein_g", "fat_g",
        "fiber_g", "amount_consumed_pct", "quality", "flags", "source"])

    mean_g = float(np.mean(sample_v)) if sample_v.size else s.baseline
    hba1c = round((mean_g + 46.7) / 28.7, 1)
    start = ORIGIN
    profile = []
    for name, label, value, unit in (
        ("age", "Age", float(40 + s.seed % 25), "years"),
        ("sex_male", "Sex (male = 1)", float(s.seed % 2), None),
        ("bmi", "BMI", round(26 + (s.seed % 7) * 1.3, 1), "kg/m²"),
        ("hba1c", "HbA1c", hba1c, "%"),
        ("fasting_glucose", "Fasting glucose", round(s.baseline - 5 + rng.normal(0, 4)), "mg/dL"),
        ("fasting_insulin", "Fasting insulin", None, "µU/mL"),
        ("triglycerides", "Triglycerides", round(float(rng.uniform(110, 220))), "mg/dL"),
        ("hdl", "HDL cholesterol", round(float(rng.uniform(35, 60))), "mg/dL"),
    ):
        profile.append({
            "name": name, "label": label, "value": value, "unit": unit, "source": SOURCE,
            "available_at": start.isoformat() if value is not None else None,
            "status": "available" if value is not None else "missing_in_source",
            "note": "Synthetic value" if value is not None else "Deliberately missing in this synthetic profile",
        })

    days_observed = (sample_t.max() - sample_t.min()) / 1440 if sample_t.size else 0.0
    meta = {
        "patient_id": s.patient_id, "display_alias": s.alias, "mode": "synthetic_demo",
        "sort_key": s.patient_id, "visible": s.visible,
        "scenario": s.description,
        "dataset": {"name": "GlucoTwin synthetic fixtures", "version": GENERATOR_VERSION, "license": LICENSE,
                    "citation_url": None, "synthetic": True},
        "cohort": {"label": "Synthetic (fictional) participant",
                   "provenance": "Generated by glucotwin.data.synthetic; not a real person or diagnosis."},
        "eligible_for_primary_analysis": False,
        "exclusion_reason": "Synthetic participants are never part of measured evaluation.",
        "primary_device": "synthetic_cgm_5min", "native_cadence_minutes": 5.0,
        "timeline_start": (ORIGIN).isoformat(),
        "timeline_end": (ORIGIN + pd.Timedelta(minutes=minutes)).isoformat(),
        "coverage": {
            "primary_device": "synthetic_cgm_5min", "native_cadence_minutes": 5.0,
            "recording_days": round(float(days_observed), 2), "glucose_samples": int(sample_t.size),
            "glucose_coverage_fraction": round(float(sample_t.size / max(1, minutes / 5)), 3),
            "gaps_over_threshold": int(np.sum(np.diff(sample_t) > 15)) if sample_t.size > 1 else 0,
            "meals_logged": len(m_rows), "activity_coverage_fraction": 1.0,
        },
        "time_policy": {
            "policy_id": "synthetic-timeline-v1",
            "description": "Fictional timeline starting 2000-01-03T00:00Z. Clock values are invented.",
            "source_timezone_known": False, "calendar_values_synthetic": True,
        },
        "availability_policy_id": "synthetic-v1",
        "notes": [f"Scenario: {s.description}.", "Synthetic data: not clinical evidence."],
    }
    return PatientData(meta, profile, glucose, activity, meals_df)


def build_store(directory) -> Store:
    store = Store(directory)
    for s in SCENARIOS:
        store.write_patient(generate(s))
    store.set_info("license", LICENSE)
    store.set_info("generator_version", GENERATOR_VERSION)
    store.set_info("mode", "synthetic_demo")
    store.log_import({"generator": GENERATOR_VERSION, "scenarios": [s.patient_id for s in SCENARIOS]})
    return store
