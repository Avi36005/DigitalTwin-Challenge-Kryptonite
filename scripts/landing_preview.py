"""Export the landing-page preview: one genuine synthetic-demonstration snapshot from the real API.

The landing page must not fabricate a patient trace, must not create sessions, and must still render when the
API is down. So the preview is captured here once — observed glucose for three hours before the replay clock and the
forecast the synthetic demonstration model actually issued at that clock — and committed as a labelled fixture.

Usage:  uv run python scripts/landing_preview.py      (needs `make synthetic`)
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from datetime import UTC, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps/web/src/content/landing-preview.json"
PATIENT, CLOCK, WINDOW_H = "SYN-B", "2000-01-03T13:00:00Z", 3


def main() -> int:
    os.environ["GLUCOTWIN_VAR_DIR"] = tempfile.mkdtemp(prefix="glucotwin-preview-")  # isolated, throwaway session
    from fastapi.testclient import TestClient
    from glucotwin_api.app import create_app

    c = TestClient(create_app())

    def get(path: str) -> dict:
        r = c.get(f"/api/v1{path}")
        r.raise_for_status()
        return r.json()

    patient = get(f"/patients/{PATIENT}")
    s = c.post("/api/v1/replay/sessions", json={"patient_id": PATIENT, "mode": "synthetic_demo"}).json()
    c.post(f"/api/v1/replay/sessions/{s['id']}/control", json={"action": "seek", "seek_to": CLOCK}).raise_for_status()
    s = get(f"/replay/sessions/{s['id']}")
    clock = datetime.fromisoformat(s["clock_at"].replace("Z", "+00:00"))
    since = clock - timedelta(hours=WINDOW_H)
    glucose, cursor = [], None
    while True:
        page = get(f"/replay/sessions/{s['id']}/events?limit=2000" + (f"&cursor={cursor}" if cursor else ""))
        for e in page["items"]:
            t = datetime.fromisoformat(e["observed_at"].replace("Z", "+00:00"))
            if e["kind"] == "glucose" and since <= t <= clock:
                glucose.append({"t": e["observed_at"], "v": e["values"]["value"]})
        cursor = page["next_cursor"]
        if not page["has_more"]:
            break
    lf = get(f"/replay/sessions/{s['id']}/forecast")
    f = lf["forecast"]
    if lf["availability"] != "available" or not f:
        print(f"no usable forecast at {CLOCK}: {lf['reasons']}", file=sys.stderr)
        return 1
    out = {
        "_note": "Generated by scripts/landing_preview.py from the synthetic demonstration (fictional data). Not a patient.",
        "generated": datetime.now(UTC).strftime("%Y-%m-%d"),
        "mode": "synthetic_demo",
        "participant": patient["display_alias"],
        "clock_at": s["clock_at"],
        "model_version": f["model_version"],
        "observed": sorted(glucose, key=lambda g: g["t"]),
        "forecasts": [
            {"horizon": e["horizon_minutes"], "target_at": e["target_at"], "value": e["predicted_mg_dl"],
             "lower": e["lower_mg_dl"], "upper": e["upper_mg_dl"], "interval_level": e["interval_level"]}
            for e in f["estimates"]
        ],
        "issued_at": f["as_of"],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(glucose)} readings, forecasts "
          + ", ".join(f"{x['horizon']} min {x['value']:.0f}" for x in out["forecasts"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
